type Service struct {
	repo       *Repository
	httpClient *http.Client
	apiKey     string
	baseURL    string
	model      string
}

func NewService(repo *Repository) *Service {
	baseURL := strings.TrimSpace(os.Getenv("DEEPSEEK_BASE_URL"))
	if baseURL == "" {
		baseURL = "https://api.deepseek.com"
	}
	model := strings.TrimSpace(os.Getenv("DEEPSEEK_MODEL"))
	if model == "" {
		model = "deepseek-chat"
	}
	return &Service{
		repo:       repo,
		httpClient: &http.Client{Timeout: 15 * time.Second},
		apiKey:     strings.TrimSpace(os.Getenv("DEEPSEEK_API_KEY")),
		baseURL:    strings.TrimRight(baseURL, "/"),
		model:      model,
	}
}

func (s *Service) RecommendDishes(ctx context.Context) ([]RecommendedDish, error) {
	stats, err := s.repo.ListRecommendationStats(ctx)
	if err != nil {
		return nil, err
	}

	recommended := make([]RecommendedDish, 0, len(stats))
	for _, item := range stats {
		score := calculateScore(item)
		recommended = append(recommended, RecommendedDish{
			DishID:        item.DishID,
			DishName:      item.DishName,
			StoreID:       item.StoreID,
			StoreName:     item.StoreName,
			Price:         item.Price,
			SalesCount:    item.SalesCount,
			OrderCount:    item.OrderCount,
			TotalQuantity: item.TotalQuantity,
			TotalAmount:   item.TotalAmount,
			Score:         score,
			Reason:        buildReason(item, score),
		})
	}

	sort.SliceStable(recommended, func(i, j int) bool {
		if recommended[i].Score == recommended[j].Score {
			if recommended[i].OrderCount == recommended[j].OrderCount {
				return recommended[i].TotalQuantity > recommended[j].TotalQuantity
			}
			return recommended[i].OrderCount > recommended[j].OrderCount
		}
		return recommended[i].Score > recommended[j].Score
	})
	return recommended, nil
}

func (s *Service) GenerateDishDescription(ctx context.Context, req DishDescriptionRequest) (DishDescriptionResponse, error) {
	req.DishName = strings.TrimSpace(req.DishName)
	req.Ingredients = strings.TrimSpace(req.Ingredients)
	req.Style = strings.TrimSpace(req.Style)
	if req.DishName == "" {
		return DishDescriptionResponse{}, fmt.Errorf("dish_name is required")
	}
	if s.apiKey == "" {
		return localDishDescription(req), nil
	}
	result, err := s.callDeepSeekText(ctx, buildDescriptionPrompt(req))
	if err != nil {
		fallback := localDishDescription(req)
		fallback.Message = "using local fallback"
		return fallback, nil
	}
	if result.Title == "" && result.Description == "" {
		fallback := localDishDescription(req)
		fallback.Message = "using local fallback"
		return fallback, nil
	}
	if result.Message == "" {
		result.Message = "generated by DeepSeek"
	}
	return result, nil
}

func (s *Service) GenerateDishImagePrompt(ctx context.Context, req DishImagePromptRequest) (DishImagePromptResponse, error) {
	req.DishName = strings.TrimSpace(req.DishName)
	req.Description = strings.TrimSpace(req.Description)
	req.Style = strings.TrimSpace(req.Style)
	if req.DishName == "" {
		return DishImagePromptResponse{}, fmt.Errorf("dish_name is required")
	}
	if s.apiKey == "" {
		return localDishImagePrompt(req), nil
	}
	result, err := s.callDeepSeekPrompt(ctx, buildImagePromptPrompt(req))
	if err != nil {
		fallback := localDishImagePrompt(req)
		fallback.Message = "using local fallback"
		return fallback, nil
	}
	if result.Prompt == "" {
		fallback := localDishImagePrompt(req)
		fallback.Message = "using local fallback"
		return fallback, nil
	}
	if result.Message == "" {
		result.Message = "generated by DeepSeek"
	}
	return result, nil
}

func calculateScore(item recommendationStat) float64 {
	return float64(item.OrderCount)*5 + float64(item.TotalQuantity)*2 + item.TotalAmount*0.12 + float64(item.SalesCount)*0.15 + item.StoreRating*3
}

func buildReason(item recommendationStat, score float64) string {
	parts := make([]string, 0, 3)
	if item.OrderCount >= 10 || item.TotalQuantity >= 20 {
		parts = append(parts, "近期下单量较高")
	}
	if item.SalesCount >= 100 {
		parts = append(parts, "历史销量靠前")
	}
	if item.StoreRating >= 4.5 {
		parts = append(parts, "所在食堂评分较高")
	}
	if len(parts) == 0 {
		parts = append(parts, "综合得分较高，适合作为热门推荐")
	}
	return strings.Join(parts, "，") + "。"
}

func localDishDescription(req DishDescriptionRequest) DishDescriptionResponse {
	style := req.Style
	if style == "" {
		style = "校园食堂"
	}
	ingredients := req.Ingredients
	if ingredients == "" {
		ingredients = "精选食材"
	}
	return DishDescriptionResponse{
		Title:           req.DishName + " - " + style + "推荐",
		Description:     fmt.Sprintf("%s融合%s，口感均衡，适合在%s场景下作为日常点餐选择。", req.DishName, ingredients, style),
		RecommendReason: fmt.Sprintf("%s风格清晰，食材组合完整，适合做成校园外卖菜单亮点。", req.DishName),
		Message:         "using local fallback",
	}
}

func localDishImagePrompt(req DishImagePromptRequest) DishImagePromptResponse {
	style := req.Style
	if style == "" {
		style = "realistic food photography"
	}
	desc := req.Description
	if desc == "" {
		desc = "fresh and appetizing"
	}
	prompt := fmt.Sprintf("A %s image of %s, %s, warm lighting, clean background, high detail, appetizing composition", style, req.DishName, desc)
	return DishImagePromptResponse{
		Prompt:         prompt,
		NegativePrompt: "blurry, low quality, distorted food, extra utensils, text, watermark",
		Note:           "当前接口生成图片提示词，不直接生成图片。真实图片生成可后续接第三方 image generation API。",
		Message:        "using local fallback",
	}
}

func buildDescriptionPrompt(req DishDescriptionRequest) string {
	return fmt.Sprintf(`请为校园食堂菜品生成 JSON 文案，字段包含 title、description、recommend_reason。\n菜品名：%s\n食材：%s\n风格：%s\n要求：中文、简洁、适合课程设计演示、不要输出多余解释。`, req.DishName, req.Ingredients, req.Style)
}

func buildImagePromptPrompt(req DishImagePromptRequest) string {
	return fmt.Sprintf(`请为食物图片生成 JSON 提示词，字段包含 prompt、negative_prompt、note。\n菜品名：%s\n描述：%s\n风格：%s\n要求：英文或中英混合均可，突出真实食物摄影，避免生成图片本身。`, req.DishName, req.Description, req.Style)
}

type deepSeekChatRequest struct {
	Model       string            `json:"model"`
	Messages    []deepSeekMessage `json:"messages"`
	Temperature float64           `json:"temperature,omitempty"`
}

type deepSeekMessage struct {
	Role    string `json:"role"`
	Content string `json:"content"`
}

type deepSeekChatResponse struct {
	Choices []struct {
		Message struct {
			Content string `json:"content"`
		} `json:"message"`
	} `json:"choices"`
}

func (s *Service) callDeepSeekText(ctx context.Context, prompt string) (DishDescriptionResponse, error) {
	content, err := s.callDeepSeek(ctx, prompt)
	if err != nil {
		return DishDescriptionResponse{}, err
	}
	var result DishDescriptionResponse
	if err := json.Unmarshal([]byte(content), &result); err != nil {
		return DishDescriptionResponse{}, err
	}
	return result, nil
}

func (s *Service) callDeepSeekPrompt(ctx context.Context, prompt string) (DishImagePromptResponse, error) {
	content, err := s.callDeepSeek(ctx, prompt)
	if err != nil {
		return DishImagePromptResponse{}, err
	}
	var result DishImagePromptResponse
	if err := json.Unmarshal([]byte(content), &result); err != nil {
		return DishImagePromptResponse{}, err
	}
	return result, nil
}

func (s *Service) callDeepSeek(ctx context.Context, prompt string) (string, error) {
	payload := deepSeekChatRequest{
		Model: s.model,
		Messages: []deepSeekMessage{
			{Role: "system", Content: "你是一个校园食堂文案助手，只输出 JSON。"},
			{Role: "user", Content: prompt},
		},
		Temperature: 0.7,
	}
	body, err := json.Marshal(payload)
	if err != nil {
		return "", err
	}
	request, err := http.NewRequestWithContext(ctx, http.MethodPost, s.baseURL+"/chat/completions", bytes.NewReader(body))
	if err != nil {
		return "", err
	}
	request.Header.Set("Content-Type", "application/json")
	request.Header.Set("Authorization", "Bearer "+s.apiKey)

	response, err := s.httpClient.Do(request)
	if err != nil {
		return "", err
	}
	defer response.Body.Close()
	if response.StatusCode >= 300 {
		return "", fmt.Errorf("deepseek status: %s", response.Status)
	}
	data, err := io.ReadAll(response.Body)
	if err != nil {
		return "", err
	}
	var chatResponse deepSeekChatResponse
	if err := json.Unmarshal(data, &chatResponse); err != nil {
		return "", err
	}
	if len(chatResponse.Choices) == 0 {
		return "", fmt.Errorf("deepseek empty response")
	}
	content := strings.TrimSpace(chatResponse.Choices[0].Message.Content)
	content = strings.TrimPrefix(content, "```json")
	content = strings.TrimPrefix(content, "```")
	content = strings.TrimSuffix(content, "```")
	return strings.TrimSpace(content), nil
}
